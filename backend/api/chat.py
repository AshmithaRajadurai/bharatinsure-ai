"""
Chat Endpoint for BharatInsure AI.
Orchestrates: Input -> Language Detection -> Memory -> Multi-Source RAG (Doc + KB) -> LLM -> Response.
"""

import time
import json
from fastapi import APIRouter, HTTPException
from fastapi.responses import StreamingResponse
from backend.models.schemas import ChatRequest, ChatResponse
from backend.services.language.detector import LanguageDetector
from backend.services.memory.session_memory import session_memory
from backend.services.rag.retriever import rag_retriever
from backend.services.rag.document_retriever import document_retriever
from backend.services.llm.llm_manager import llm_manager, DISCLAIMER_TEXT
from backend.services.intent.intent_router import intent_router

router = APIRouter()

@router.post("/chat", response_model=ChatResponse)
async def chat_endpoint(request: ChatRequest):
    if not request.message or not request.message.strip():
        raise HTTPException(status_code=400, detail="Message cannot be empty.")

    # 1. Automatic Language Detection
    if request.language and request.language != "auto":
        detected_lang = request.language
    else:
        detected_lang, _ = LanguageDetector.detect(request.message)

    lang_info = LanguageDetector.get_language_info(detected_lang)
    session_id = request.session_id or "default-session"

    # 2. Fast Intent Routing for basic queries (Greetings, Identity, Capabilities)
    # Bypasses RAG and LLM for pure conversational queries in < 1ms, while domain finance questions proceed to retrieval.
    intent_match = intent_router.route(request.message, detected_language=detected_lang)
    if intent_match:
        session_memory.add_turn(
            session_id=session_id,
            user_content=request.message,
            assistant_content=intent_match["response"],
            user_lang=detected_lang,
            category="Conversational"
        )
        return ChatResponse(
            response=intent_match["response"],
            session_id=session_id,
            detected_language=detected_lang,
            language_name=lang_info["name"],
            language_flag=lang_info["flag"],
            sources=[],
            model_used=intent_match["model_used"],
            latency_ms=0.5,
            input_type=request.input_type or "text",
            audio_base64=None,
            disclaimer=DISCLAIMER_TEXT,
            active_document=None
        )

    # 3. Retrieve Conversation Memory & History (compact to preserve speed)
    history_text = session_memory.format_history_for_prompt(session_id, limit=2)

    # 3. Check for Active Uploaded Document in Session
    active_doc_info = document_retriever.get_document_info(session_id)
    active_doc_name = active_doc_info["document_name"] if active_doc_info else None

    # 4. Multi-Source Insurance RAG Retrieval (Uploaded Document + Base Knowledge Base)
    sources = rag_retriever.retrieve_multi_source(
        query=request.message,
        session_id=session_id,
        top_k=3
    )

    # Inferred topic category for memory tagging
    top_category = sources[0].category if sources else "General Insurance"

    # 5. Multilingual LLM Generation with Active Document Grounding
    llm_result = llm_manager.generate_response(
        query=request.message,
        detected_language=detected_lang,
        sources=sources,
        conversation_history_text=history_text,
        model_preference=request.model_preference or "api",
        active_document=active_doc_name
    )

    # 6. Save Turn to Conversational Memory (maintaining cross-lingual dialogue)
    session_memory.add_turn(
        session_id=session_id,
        user_content=request.message,
        assistant_content=llm_result["response"],
        user_lang=detected_lang,
        category=top_category
    )

    return ChatResponse(
        response=llm_result["response"],
        session_id=session_id,
        detected_language=detected_lang,
        language_name=lang_info["name"],
        language_flag=lang_info["flag"],
        sources=sources,
        model_used=llm_result["model_used"],
        latency_ms=llm_result["latency_ms"],
        input_type=request.input_type or "text",
        audio_base64=None,
        disclaimer=DISCLAIMER_TEXT,
        active_document=active_doc_name
    )


@router.post("/chat/stream")
async def chat_stream_endpoint(request: ChatRequest):
    """
    Streaming chat endpoint for low perceived latency on local CPU inference.
    Yields Server-Sent Events (SSE) tokens directly as generated by Ollama.
    """
    if not request.message or not request.message.strip():
        raise HTTPException(status_code=400, detail="Message cannot be empty.")

    t_start = time.time()

    # 1. Automatic Language Detection
    if request.language and request.language != "auto":
        detected_lang = request.language
    else:
        detected_lang, _ = LanguageDetector.detect(request.message)

    lang_info = LanguageDetector.get_language_info(detected_lang)
    session_id = request.session_id or "default-session"

    # 2. Fast Intent Routing for basic queries
    intent_match = intent_router.route(request.message, detected_language=detected_lang)
    if intent_match:
        session_memory.add_turn(
            session_id=session_id,
            user_content=request.message,
            assistant_content=intent_match["response"],
            user_lang=detected_lang,
            category="Conversational"
        )
        async def fast_stream():
            meta = {
                "type": "meta",
                "detected_language": detected_lang,
                "language_name": lang_info["name"],
                "language_flag": lang_info["flag"],
                "sources": [],
                "model_used": intent_match["model_used"],
                "active_document": None
            }
            yield f"data: {json.dumps(meta)}\n\n"
            yield f"data: {json.dumps({'type': 'token', 'token': intent_match['response']})}\n\n"
            done_payload = {
                "type": "done",
                "latency_ms": 0.5,
                "ttft_ms": 0.5,
                "response": intent_match["response"]
            }
            yield f"data: {json.dumps(done_payload)}\n\n"

        return StreamingResponse(fast_stream(), media_type="text/event-stream")

    # 3. Retrieve Memory and Active Document
    history_text = session_memory.format_history_for_prompt(session_id, limit=2)
    active_doc_info = document_retriever.get_document_info(session_id)
    active_doc_name = active_doc_info["document_name"] if active_doc_info else None

    # 4. Multi-Source Insurance RAG Retrieval
    sources = rag_retriever.retrieve_multi_source(
        query=request.message,
        session_id=session_id,
        top_k=2
    )
    top_category = sources[0].category if sources else "General Insurance"

    # 5. Generator yielding SSE tokens
    def sse_event_stream():
        meta_payload = {
            "type": "meta",
            "detected_language": detected_lang,
            "language_name": lang_info["name"],
            "language_flag": lang_info["flag"],
            "sources": [s.model_dump() for s in sources],
            "model_used": f"{llm_manager.local_llm.model_name if hasattr(llm_manager, 'local_llm') else 'qwen2.5:3b'} (Ollama Local LLM)",
            "active_document": active_doc_name
        }
        yield f"data: {json.dumps(meta_payload)}\n\n"

        accumulated = []
        measured_ttft = None
        for chunk, ttft, done in llm_manager.generate_response_stream(
            query=request.message,
            detected_language=detected_lang,
            sources=sources,
            conversation_history_text=history_text,
            model_preference=request.model_preference or "local_small",
            active_document=active_doc_name
        ):
            if ttft and measured_ttft is None:
                measured_ttft = ttft
            if chunk:
                accumulated.append(chunk)
                yield f"data: {json.dumps({'type': 'token', 'token': chunk})}\n\n"

        full_response = "".join(accumulated)
        total_latency = round((time.time() - t_start) * 1000, 1)

        # Save turn to memory
        session_memory.add_turn(
            session_id=session_id,
            user_content=request.message,
            assistant_content=full_response,
            user_lang=detected_lang,
            category=top_category
        )

        done_meta = {
            "type": "done",
            "latency_ms": total_latency,
            "ttft_ms": measured_ttft or total_latency,
            "response": full_response
        }
        yield f"data: {json.dumps(done_meta)}\n\n"

    return StreamingResponse(sse_event_stream(), media_type="text/event-stream")

